# UX팀 지침

## 결정은 사람이 한다
- 에이전트는 열거하고, 찾고, 만든다. 고르지 않는다.
- 근거가 없는 판단은 채우지 않고 `미결`로 남긴다.
- 미결이 0건인 문서는 다시 본다. 처음 만드는 화면에서 모르는 것이 하나도 없을 수는 없다.

## 정본은 하나다
- 화면의 생김새와 배치는 figma, 동작·조건·예외·정책은 요구사항 목록이 정본이다.
- 팀 결정·용어·상충은 ClickUp 중앙 컨텍스트, 티키타 정책은 정책 위키(`tikita-policy`)가 정본이다.
- 두 정본이 어긋나면 한쪽으로 맞추지 않고 차이를 적는다.
- 회의 결정이 문서 코멘트보다 우선한다.

## ID
- 자체 ID는 대문자 3글자 접두어와 두 자리 번호로 붙이고, 문서 맨 앞에 범례를 둔다.
- 자주 쓰는 접두어: `REQ` 요구사항 · `DEC` 결정 · `QST` 미결 질문 · `ASM` 가정 · `RSK` 위험
- 한 번 붙인 번호는 바꾸지 않고, 뺀 번호는 비워 둔다.

## 팀에 보내는 글
- 결론부터 쓴다. 판단할 것 → 확인할 것 → 참고 순서로 둔다.
- 서술 문장은 문장마다 줄을 바꾼다. 불릿은 예외다.
- 사람이 확인하기 전에는 "확정"이라고 쓰지 않는다.
- 기록은 ClickUp 댓글에 남기고, Slack은 그 링크를 알리는 데만 쓴다.
- 쓰거나 보내기 전에 초안을 보여 주고 확인받는다.

## 교차 지점
- 입구: 배정된 프로젝트는 팀 스페이스에 상위 태스크로 등록한다 (`kickoff`).
- CRS-03 중간 확인: 막히면 상위 태스크 댓글로 리드를 부른다 (`call-lead`).
- CRS-04 핸즈오프: 의도대로 동작하는지 확인하고, 글과 아티팩트를 맞춘 뒤 넘긴다 (`handoff-check`).
- CRS-05 최종 확인: staging 화면을 기획 의도와 대조한다 (`intent-check`).
- 결정이 나면 중앙 컨텍스트에 남긴다 (`decision-log`).
- CRS-NN은 팀 파이프라인 문서의 교차 지점 번호다: https://claude.ai/artifact/1sbYWBaa5a4LiXaYjVRKhk
EOF_GUIDE
